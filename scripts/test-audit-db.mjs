// Run with an absolute module path to an isolated @electric-sql/pglite 0.5.8 install.
import { pathToFileURL, fileURLToPath } from 'node:url';
const { PGlite } = await import(pathToFileURL(process.argv[2]).href);
import { readFileSync, readdirSync } from 'node:fs';
import assert from 'node:assert/strict';
const db = new PGlite();
await db.exec(`
create role anon; create role authenticated; create schema auth;
create function auth.uid() returns uuid language sql as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
create table stores(id uuid primary key, access_code text, business_type text, subscription_status text);
create table store_members(store_id uuid, profile_id uuid);
create function public.is_store_member(uuid) returns boolean language sql security definer as $$select exists(select 1 from public.store_members where store_id=$1 and profile_id=auth.uid())$$;
create function public.check_rate_limit(text,text,integer,integer) returns void language sql as $$select$$;
create table orders(id uuid primary key default gen_random_uuid(),store_id uuid,customer_name text,customer_phone text,order_number text,status text,subtotal numeric,discount numeric,total numeric,notes text,business_type text,order_kind text,workflow_stage text,service_metadata jsonb,client_ref text,updated_at timestamptz,access_token uuid default gen_random_uuid(),unique(store_id,client_ref));
create table order_items(id uuid default gen_random_uuid(),order_id uuid,product_id text,offering_id text,item_kind text,item_name text,unit text,quantity numeric,price numeric,subtotal numeric,options jsonb,metadata jsonb);
create table laundry_order_items(order_id uuid,store_id uuid,garment_type text,tag_code text,quantity numeric,special_instructions text,workflow_stage text,metadata jsonb,updated_at timestamptz);
grant usage on schema public,auth to anon,authenticated;
insert into stores values ('00000000-0000-0000-0000-000000000001','SHOPA','laundry','active'),('00000000-0000-0000-0000-000000000002','SHOPB','laundry','active');
insert into store_members values ('00000000-0000-0000-0000-000000000001','10000000-0000-0000-0000-000000000001');
`);
const dir=fileURLToPath(new URL('../supabase/migrations', import.meta.url));
const file=readdirSync(dir).find(x=>x.endsWith('_audit_authorization_hardening.sql'));
await db.exec(readFileSync(`${dir}/${file}`,'utf8'));
let count=0;
async function denied(sql, code='42501') { await assert.rejects(()=>db.query(sql),e=>e.code===code); count++; }
const create=(shop='SHOPA',ref='ref1',phone='')=>`select create_laundry_walkin_v2('${shop}','${ref}','ABC234','Customer','${phone}','wash','Wash','per_piece',1,100,'{}','[{"garment_type":"shirt","quantity":1,"unit_price":100,"subtotal":100}]') result`;
await db.exec('set role anon');
await denied(create());
await denied("select update_laundry_walkin_stage('SHOPA','ref1','collected')");
await db.exec("set role authenticated; select set_config('request.jwt.claim.sub','10000000-0000-0000-0000-000000000001',false)");
await denied(create('SHOPB'));
await denied("select update_laundry_walkin_stage('SHOPB','ref1','collected')");
const created=(await db.query(create())).rows[0].result;
assert.equal(created.already_synced,false); count++;
assert.equal((await db.query(create())).rows[0].result.already_synced,true); count++;
await assert.rejects(()=>db.query(create('SHOPA','badphone','123').replace('ABC234','ABC235')),/phone number is invalid/); count++;
await db.query("select update_laundry_walkin_stage('SHOPA','ref1','collected')"); count++;
await db.exec('reset role');
const order=(await db.query('select * from orders')).rows[0];
assert.equal(order.customer_phone,''); assert.equal(order.status,'Completed'); count++;
await db.exec("update orders set status='Pending'; set role anon");
await denied(`select customer_cancel_order('${order.id}','')`);
await denied(`select customer_cancel_order('${order.id}','','','wrong')`);
await denied(`select customer_approve_order_changes('${order.id}','')`);
await db.query(`select customer_approve_order_changes('${order.id}','','${order.access_token}')`); count++;
await db.query(`select customer_cancel_order('${order.id}','','','${order.access_token}')`); count++;
console.log(`${count} PostgreSQL authorization and laundry contract checks passed`);
await db.exec(`reset role;
alter table stores add column data jsonb;
alter table orders add column status_history jsonb, add column customer_uuid uuid, add column is_guest boolean;
create table products(id uuid,store_id uuid,status text,quantity numeric,selling_price numeric,is_service boolean);
insert into products values ('20000000-0000-0000-0000-000000000001','00000000-0000-0000-0000-000000000001','active',20,100,false);
update stores set data='{"products":[],"businessTemplate":{"offerings":[{"id":"service-test","price":80},{"id":"30000000-0000-0000-0000-000000000001","price":90}]}}' where access_code='SHOPA';
`);
const checkoutFile=readdirSync(dir).find(x=>x.endsWith('_audit_checkout_totals.sql'));
await db.exec(readFileSync(`${dir}/${checkoutFile}`,'utf8'));
await db.exec('set role anon');
let sequence=0;
const checkout=(total=100, price=100, id='20000000-0000-0000-0000-000000000001', notes='{}', status='Pending')=>`select place_order_atomic('00000000-0000-0000-0000-000000000001','Customer','123456789','order-${++sequence}','${status}',${price},${total},'${notes}','[{"product_id":"${id}","quantity":1,"price":${price},"subtotal":${price}}]')`;
await assert.rejects(()=>db.query(checkout(0)),/Order total/); count++;
await assert.rejects(()=>db.query(checkout(100,1)),/Price changed/); count++;
await assert.rejects(()=>db.query(checkout(1,1,undefined,'{"pricing_mode":"wholesale"}')),/Price changed/); count++;
await assert.rejects(()=>db.query(checkout(100,100,undefined,'{}','Completed')),/start Pending/); count++;
await db.query(checkout()); count++;
await db.query(checkout(80,80,'service-test')); count++;
await db.query(checkout(90,90,'30000000-0000-0000-0000-000000000001')); count++;
await assert.rejects(()=>db.query(checkout(1,1,'30000000-0000-0000-0000-000000000001')),/Price changed/); count++;
await db.exec('reset role');
assert.equal(Number((await db.query("select total from orders where order_number like 'order-%' order by total limit 1")).rows[0].total),80); count++;
console.log(`${count} total PostgreSQL checks passed, including checkout tampering and service prices`);
await db.close();


